txt = open(f'{root}/opendbc/dbc/ford_lincoln_base_pt.dbc', encoding='latin-1').read()
msgs, cur = {}, None
for l in txt.split('\n'):
    m = re.match(r'BO_ (\d+) (\w+): (\d+) (\w+)', l)
    if m:
        a = int(m.group(1)); cur = a if a in want else None
        if cur is not None: msgs[a] = dict(id=a, name=m.group(2), dlc=int(m.group(3)), sender=m.group(4), signals=[])
        continue
    if cur is not None:
        s = re.match(r'\s*SG_ (\w+) : (\d+)\|(\d+)@([01])([+-]) \(([^,]+),([^)]+)\) \[[^\]]*\] "([^"]*)"\s+(.*)', l)
        if s and s.group(1) in want[cur]:
            msgs[cur]['signals'].append(dict(name=s.group(1), start=int(s.group(2)), length=int(s.group(3)),
              endian='big' if s.group(4) == '0' else 'little', signed=s.group(5) == '-', scale=float(s.group(6)), offset=float(s.group(7)),
              unit=s.group(8), receivers=[r for r in s.group(9).strip().split(',') if r and r != 'Vector__XXX']))
for m in re.finditer(r'^BA_ "GenMsgCycleTime" BO_ (\d+) (\d+);', txt, re.M):
    a = int(m.group(1))
    if a in msgs: msgs[a]['cycleMs'] = int(m.group(2))
vals = {}
for m in re.finditer(r'^VAL_ (\d+) (\w+) (.*);', txt, re.M):
    a, n = int(m.group(1)), m.group(2)
    if a in want and n in want[a]:
        vals[(a, n)] = {int(k): v for k, v in re.findall(r'(\d+) "([^"]*)"', m.group(3))}
for a, msg in msgs.items():
    msg['signals'].sort(key=lambda s: want[a].index(s['name']))
    for s in msg['signals']:
        if (a, s['name']) in vals: s['values'] = vals[(a, s['name'])]
        for k in ('scale', 'offset'):
            if s[k] == int(s[k]): s[k] = int(s[k])
    assert len(msg['signals']) == len(want[a]), (hex(a), [s['name'] for s in msg['signals']])
out = [msgs[a] for a in sorted(msgs)]
print('// GENERATED by scripts/gen-ford.py from opendbc/dbc/ford_lincoln_base_pt.dbc (commaai/opendbc, MIT license,')
print(f'// commit {commit}). Do not edit by hand.')
